    probe_client.force_login(owner)
    assert probe_client.get("/probe/").json()["companies"] == ["Acme Sdn Bhd"]

    probe_client.force_login(other)
    assert probe_client.get("/probe/").json()["companies"] == ["Beta Trading"]


